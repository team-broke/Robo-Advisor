"""Repository-reviewed, research-only authorization for PPO inputs."""

from __future__ import annotations

import json
import hashlib
import os
from pathlib import Path
import re
import tempfile
import inspect

import pandas as pd
import yaml

# This path is repository owned. A caller-supplied spec is evidence, not authority.
RESEARCH_REGISTRY = Path(__file__).resolve().parents[3] / "config" / "research_datasets.yaml"
_DIGEST = re.compile(r"[0-9a-f]{64}\Z")
_REVIEW = re.compile(r"https://github\.com/team-broke/Robo-Advisor/(?:issues|pull)/[1-9][0-9]*\Z")
_FILES = {"returns.parquet", "rsi.parquet", "macd.parquet"}
_TEST_FIXTURES = {
    "test_training.py",
    "test_retrain.py",
    "test_backtest_comparison.py",
    "test_ppo_reproducibility.py",
    "test_progress.py",
    "test_curves.py",
    "test_evaluation.py",
    "test_validation_selection.py",
    "test_reward_sweep.py",
}
_SYNTHETIC_FIXTURE_HASHES = {}


def _test_fixture_source():
    if "PYTEST_CURRENT_TEST" not in os.environ:
        raise ValueError("synthetic fixture registration is available only to pytest")
    tests_root = Path(__file__).resolve().parents[3] / "tests"
    active_test = Path(os.environ["PYTEST_CURRENT_TEST"].split("::", 1)[0]).name
    for frame in inspect.stack()[1:]:
        source = Path(frame.filename).resolve()
        if source.parent == tests_root and source.name == active_test:
            if source.name in _TEST_FIXTURES:
                return source
            break
    raise ValueError("synthetic fixture must come from the active reviewed repository test")


def _synthetic_hashes(directory):
    from robo_advisor.features.dataset import TEAM12_ASSETS
    from robo_advisor.ops.ppo_preflight import NATIVE_FILES, RISK_FILE, _load_dataset

    files = {name: (directory / name).read_bytes() for name in NATIVE_FILES}
    dataset = _load_dataset(files)
    hashes = dataset.file_sha256.copy()
    if (directory / RISK_FILE).exists():
        # The native loader deliberately ignores post-cutoff risk events.
        hashes[RISK_FILE] = hashlib.sha256((directory / RISK_FILE).read_bytes()).hexdigest()
    if list(dataset.returns.columns) == list(TEAM12_ASSETS):
        raise ValueError("Team12 financial inputs cannot use the synthetic fixture path")
    return hashes


def register_synthetic_test_fixture(directory):
    """Bind bytes generated by a reviewed pytest fixture; never called by production entrypoints."""
    source = _test_fixture_source()
    directory = Path(directory).resolve()
    if not directory.is_relative_to(Path(tempfile.gettempdir()).resolve()):
        raise ValueError("synthetic fixture data must be isolated in the pytest temp root")
    _SYNTHETIC_FIXTURE_HASHES[directory] = (_synthetic_hashes(directory), source.name)


def authorize_synthetic_fixture(config, *, smoke, preflight_spec=None):
    """Allow only registered repository pytest fixtures, bound to temporary input bytes.

    This is a test-process capability, not a user-facing smoke or manifest switch.
    A Python caller able to modify repository test code can also modify the gate;
    repository review is the trust boundary.
    """
    if not smoke or "PYTEST_CURRENT_TEST" not in os.environ:
        raise ValueError("synthetic training requires a trusted test fixture")
    source = _test_fixture_source()
    directory = config.data.dataset_dir.expanduser().resolve()
    if not directory.is_relative_to(Path(tempfile.gettempdir()).resolve()):
        raise ValueError("synthetic fixture data must be isolated in the pytest temp root")
    registered = _SYNTHETIC_FIXTURE_HASHES.get(directory)
    if registered is None or registered[1] != source.name:
        raise ValueError("synthetic fixture has no reviewed test registration")
    hashes = _synthetic_hashes(directory)
    if hashes != registered[0]:
        raise ValueError("synthetic fixture bytes changed after registration")
    checked = None
    if preflight_spec is not None:
        from robo_advisor.ops.ppo_preflight import check_inputs

        path = Path(preflight_spec).resolve(strict=True)
        spec = json.loads(path.read_text(encoding="utf-8"))
        if not isinstance(spec, dict) or spec.get("kind") != "synthetic":
            raise ValueError("synthetic fixture requires a synthetic preflight specification")
        checked = check_inputs(spec, path.parent, check_environments=False)
        if (
            checked.result["technical_status"] != "passed"
            or checked.result["source_status"] == "failed"
        ):
            raise ValueError(f"synthetic preflight rejected input: {checked.result['reasons']}")
        expected = checked.config.model_dump(mode="json")
        expected["data"]["dataset_dir"] = str(
            (path.parent / expected["data"]["dataset_dir"]).resolve()
        )
        actual = config.model_dump(mode="json")
        actual["data"]["dataset_dir"] = str(directory)
        if expected != actual or checked.dataset.file_sha256 != hashes:
            raise ValueError("synthetic fixture differs from preflight evidence")
    return {
        "kind": "synthetic_test",
        "dataset_id": None,
        "review_ref": registered[1],
        "limitations": ["repository pytest fixture only; no financial performance claim"],
        "technical_status": "passed",
        "source_status": "synthetic",
        "file_sha256": hashes,
        "training_approved": False,
    }, checked


def _registry():
    with RESEARCH_REGISTRY.open(encoding="utf-8") as stream:
        document = yaml.safe_load(stream)
    if not isinstance(document, dict) or set(document) != {"schema_version", "research_datasets"}:
        raise ValueError("invalid research dataset registry")
    if document["schema_version"] != 1 or not isinstance(document["research_datasets"], list):
        raise ValueError("invalid research dataset registry version or entries")
    entries = {}
    for entry in document["research_datasets"]:
        required = {
            "dataset_id",
            "file_sha256",
            "allowed_train_start",
            "allowed_train_end",
            "review_ref",
            "limitations",
        }
        if not isinstance(entry, dict) or set(entry) != required:
            raise ValueError("invalid research dataset entry")
        dataset_id = entry["dataset_id"]
        hashes = entry["file_sha256"]
        if not isinstance(dataset_id, str) or not re.fullmatch(
            r"[A-Za-z0-9][A-Za-z0-9_.-]*", dataset_id
        ):
            raise ValueError("invalid research dataset ID")
        if (
            dataset_id in entries
            or not isinstance(hashes, dict)
            or set(hashes) not in (_FILES, _FILES | {"risk_tags.parquet"})
            or any(
                not isinstance(value, str) or not _DIGEST.fullmatch(value)
                for value in hashes.values()
            )
        ):
            raise ValueError("invalid or duplicate research dataset hashes")
        if not isinstance(entry["review_ref"], str) or not _REVIEW.fullmatch(entry["review_ref"]):
            raise ValueError("research review must reference this repository's PR or issue")
        if (
            not isinstance(entry["limitations"], list)
            or not entry["limitations"]
            or any(not isinstance(item, str) or not item.strip() for item in entry["limitations"])
        ):
            raise ValueError("research limitations must be explicit")
        start, end = (
            pd.Timestamp(entry[name]) for name in ("allowed_train_start", "allowed_train_end")
        )
        if start.tzinfo is None or end.tzinfo is None or start > end:
            raise ValueError("research interval must be ordered and timezone-aware")
        entries[dataset_id] = entry
    return entries


def authorize_research(config, preflight_spec):
    """Check approval before preflight constructs environments or training outputs."""
    if preflight_spec is None:
        raise ValueError("research training requires a preflight specification")
    # Lazy import avoids the existing preflight -> training import cycle.
    from robo_advisor.ops.ppo_preflight import check_inputs

    path = Path(preflight_spec).resolve(strict=True)
    spec = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(spec, dict) or spec.get("kind") != "research":
        raise ValueError("research training requires a research preflight specification")
    entry = _registry().get(spec.get("dataset_id"))
    if entry is None:
        raise ValueError("dataset is absent from the reviewed research registry")
    root = path.parent
    checked = check_inputs(spec, root, check_environments=False)
    report = checked.result
    if report["technical_status"] != "passed" or report["source_status"] == "failed":
        raise ValueError(f"research preflight rejected input: {report['reasons']}")
    if checked.config is None or checked.dataset is None:
        raise ValueError("research preflight did not return checked inputs")
    actual = config.model_dump(mode="json")
    expected = checked.config.model_dump(mode="json")
    expected["data"]["dataset_dir"] = str((root / expected["data"]["dataset_dir"]).resolve())
    actual["data"]["dataset_dir"] = str(config.data.dataset_dir.expanduser().resolve())
    if actual != expected:
        raise ValueError("training config differs from the reviewed preflight config")
    hashes = checked.dataset.file_sha256
    if hashes != entry["file_sha256"]:
        raise ValueError("PPO input hashes differ from the reviewed research registry")
    if config.data.train_start is None:
        raise ValueError("reviewed research training requires an explicit start")
    start, end = pd.Timestamp(config.data.train_start), pd.Timestamp(config.data.train_end)
    if start < pd.Timestamp(entry["allowed_train_start"]) or end > pd.Timestamp(
        entry["allowed_train_end"]
    ):
        raise ValueError("training period exceeds the reviewed research interval")
    return {
        "kind": "research",
        "dataset_id": spec["dataset_id"],
        "review_ref": entry["review_ref"],
        "limitations": entry["limitations"],
        "technical_status": report["technical_status"],
        "source_status": report["source_status"],
        "file_sha256": hashes,
        "training_approved": False,
    }, checked


def validate_research_environments(checked):
    """Run the environment checks only after the native loader confirms the approved bytes."""
    from robo_advisor.ops.ppo_preflight import _check_environments

    bounds = [(pd.Timestamp(period.start), pd.Timestamp(period.end)) for period in checked.periods]
    return _check_environments(checked.dataset, checked.config, bounds)
